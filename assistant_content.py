def tip_of_the_day(bank: list, seed_date: date = None) -> str:
    """Детермінований вибір поради за датою — без випадкових повторів."""
    d = seed_date or date.today()
    return bank[d.toordinal() % len(bank)]


def milestone_message(day_count: int) -> str | None:
    """Повертає milestone-повідомлення для стріку, якщо день — рубіжний."""
    if day_count in ALCOHOL_MILESTONES:
        return ALCOHOL_MILESTONES[day_count]
    # найближчий наступний рубіж
    future = [m for m in sorted(ALCOHOL_MILESTONES) if m > day_count]
    if future:
        nxt = future[0]
        return f"До рубежу {nxt} днів: ще {nxt - day_count}."
    return None
